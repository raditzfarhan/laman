// Package caddyconf renders the Caddyfile for laman's embedded Caddy server
// and turns it into Caddy's JSON config.
package caddyconf

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"

	"github.com/caddyserver/caddy/v2/caddyconfig/caddyfile"
	"github.com/caddyserver/caddy/v2/caddyconfig/httpcaddyfile"

	"laman/internal/sites"
)

type Input struct {
	HTMLDir    string // landing page served for unknown hosts
	LogFile    string
	StorageDir string // Caddy's own state (kept inside LAMAN_HOME)
	HTTPPort   int
	PHPPorts   []int            // default PHP pool
	SitePorts  map[string][]int // per-host pool, overriding PHPPorts
	Sites      []sites.Site
	// SiteEnv: server variables handed to PHP for a host on every request
	// (an app's secrets; visitors cannot set server variables).
	SiteEnv map[string]map[string]string
	// Shares: sites reachable through a tunnel (`laman share`).
	Shares []Share
	// DevPorts: the port of each running dev server, by host. A Node site
	// without one shows its notice page (stopped, starting, crashed).
	DevPorts map[string]int
	// DomainPort: where the user's own-domain tunnel delivers requests;
	// shares with a Hostname are routed there by host name. 0 when off.
	DomainPort int

	// HTTPS: when HTTPSPort > 0, sites with an entry in Certs (keyed by
	// host) are also served over TLS. DefaultCert covers localhost and any
	// unknown SNI name.
	HTTPSPort   int
	Certs       map[string]Cert
	DefaultCert Cert
}

type Cert struct{ Crt, Key string }

// Share serves the site with Host on 127.0.0.1:Port, for a tunnel.
// A share with a Hostname (own domain) is served at that name on
// DomainPort instead.
type Share struct {
	Host     string
	Port     int
	Hostname string
}

// q quotes a value for the Caddyfile, using forward slashes for paths.
func q(s string) string {
	s = strings.ReplaceAll(filepath.ToSlash(s), `"`, `\"`)
	return `"` + s + `"`
}

func Render(in Input) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	https := in.HTTPSPort > 0 && in.DefaultCert.Crt != ""

	w("# Generated by laman. Edits are overwritten on every reload.")
	w("{")
	w("\tadmin off")
	w("\tpersist_config off")
	w("\tauto_https off") // laman's own CA issues every certificate
	w("\tstorage file_system %s", q(in.StorageDir))
	w("\thttp_port %d", in.HTTPPort)
	if in.HTTPSPort > 0 {
		w("\thttps_port %d", in.HTTPSPort)
	}
	if https {
		w("\tdefault_sni localhost")
	}
	w("\tgrace_period 3s")
	w("\tlog {")
	w("\t\toutput file %s {", q(in.LogFile))
	w("\t\t\troll_size 10MiB")
	w("\t\t\troll_keep 3")
	w("\t\t}")
	w("\t\tlevel WARN")
	w("\t}")
	w("}")

	upstreamsFor := func(host string) string {
		ports, ok := in.SitePorts[host]
		if !ok {
			ports = in.PHPPorts
		}
		out := make([]string, len(ports))
		for i, p := range ports {
			out[i] = fmt.Sprintf("127.0.0.1:%d", p)
		}
		return strings.Join(out, " ")
	}

	// Caddy needs plain-HTTP and TLS addresses in separate blocks, so each
	// site body is written once per scheme.
	block := func(addrs string, cert *Cert, body func()) {
		w("%s {", addrs)
		w("\tbind 127.0.0.1")
		if cert != nil {
			w("\ttls %s %s", q(cert.Crt), q(cert.Key))
		}
		body()
		w("}")
	}

	// Unknown hosts and localhost get the landing page.
	landing := func() {
		w("\troot * %s", q(in.HTMLDir))
		w("\tfile_server")
	}
	w("")
	block(fmt.Sprintf("http://:%d", in.HTTPPort), nil, landing)
	if https {
		// Catch-all: any SNI without its own site (typos, localhost, IPs).
		block(fmt.Sprintf("https://:%d", in.HTTPSPort), &in.DefaultCert, landing)
	}

	// notice serves the site's page from HTMLDir/notice (written by the
	// daemon) for every request: what the folder is and what to do.
	noticeDir := filepath.Join(in.HTMLDir, "notice")
	notice := func(s sites.Site, status string) {
		w("	header X-Laman-Notice %s", s.Kind)
		w("	root * %s", q(noticeDir))
		w("	rewrite * /%s.html", s.Name)
		w("	file_server {")
		w("		status %s", status)
		w("	}")
	}
	// proxy forwards to a dev server or a `laman proxy` port. The upstream
	// sees Host localhost:<port>, which dev servers (Vite, Nuxt) accept
	// without any allowedHosts setting; X-Forwarded-Host keeps the name.
	proxy := func(s sites.Site, target string) {
		w("	reverse_proxy %s {", target)
		w("		header_up Host {upstream_hostport}")
		w("		flush_interval -1") // stream server-sent events and logs
		w("	}")
		w("	handle_errors 502 503 504 {")
		w("		header X-Laman-Notice %s", s.Kind)
		w("		root * %s", q(noticeDir))
		w("		rewrite * /%s.html", s.Name)
		w("		file_server {")
		w("			status {err.status_code}")
		w("		}")
		w("	}")
	}

	// siteBody serves one site; env is handed to its PHP as server variables.
	siteBody := func(s sites.Site, env map[string]string) func() {
		return func() {
			switch s.Kind {
			case sites.KindProxy:
				proxy(s, s.Proxy)
				return
			case sites.KindNode:
				if port, ok := in.DevPorts[s.Host]; ok {
					// localhost, not 127.0.0.1: Node often listens on ::1 only.
					proxy(s, fmt.Sprintf("localhost:%d", port))
				} else {
					notice(s, "503")
				}
				return
			case sites.KindGroup, sites.KindNone:
				notice(s, "404")
				return
			}
			w("\troot * %s", q(s.Root))
			w("\t@hidden {")
			w("\t\tpath */.*")
			w("\t\tnot path /.well-known/*")
			w("\t}")
			w("\trespond @hidden 403")
			w("\tphp_fastcgi %s {", upstreamsFor(s.Host))
			if !s.Front {
				// No front controller: only real .php files go to PHP, so
				// static sites serve index.html and return real 404s.
				w("\t\tindex off")
			}
			keys := make([]string, 0, len(env))
			for k := range env {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for _, k := range keys {
				w("\t\tenv %s %s", k, q(env[k]))
			}
			w("\t\tlb_policy least_conn")
			w("\t\tlb_try_duration 5s") // ride out a php-cgi worker restarting
			w("\t\tread_timeout 300s")
			w("\t}")
			w("\tfile_server")
		}
	}

	for _, s := range in.Sites {
		site := siteBody(s, in.SiteEnv[s.Host])
		w("")
		if s.PHP != "" {
			w("# %s -> %s (PHP %s)", s.Host, filepath.ToSlash(s.Path), s.PHP)
		} else {
			w("# %s -> %s", s.Host, filepath.ToSlash(s.Path))
		}
		block(fmt.Sprintf("http://%s:%d", s.Host, in.HTTPPort), nil, site)
		if cert, ok := in.Certs[s.Host]; ok && in.HTTPSPort > 0 {
			block(fmt.Sprintf("https://%s:%d", s.Host, in.HTTPSPort), &cert, site)
		}
	}

	// Shared sites: a private port per share, answering any host name (the
	// tunnel's), serving only that site. The tunnel ends HTTPS, so PHP is
	// told the request is secure; app keys are never passed here.
	for _, sh := range in.Shares {
		for _, s := range in.Sites {
			if s.Host != sh.Host || s.App != "" {
				continue
			}
			w("")
			w("# shared: %s", s.Host)
			addr := fmt.Sprintf("http://:%d", sh.Port)
			if sh.Hostname != "" {
				if in.DomainPort <= 0 {
					continue
				}
				addr = fmt.Sprintf("http://%s:%d", sh.Hostname, in.DomainPort)
			}
			block(addr, nil, siteBody(s, map[string]string{"HTTPS": "on"}))
		}
	}
	if in.DomainPort > 0 {
		// Addresses on the user's domain that are not shared right now.
		w("")
		block(fmt.Sprintf("http://:%d", in.DomainPort), nil, func() {
			w("\trespond \"Not shared right now.\" 404")
		})
	}
	return b.String()
}

// Adapt converts a Caddyfile to Caddy's native JSON config.
func Adapt(caddyfileText string) ([]byte, error) {
	adapter := caddyfile.Adapter{ServerType: httpcaddyfile.ServerType{}}
	out, warnings, err := adapter.Adapt([]byte(caddyfileText), map[string]any{"filename": "Caddyfile"})
	if err != nil {
		return nil, err
	}
	for _, w := range warnings {
		// Caddy warns about formatting only; laman generates the file.
		if !strings.Contains(w.Message, "formatted") {
			return nil, fmt.Errorf("caddyfile line %d: %s", w.Line, w.Message)
		}
	}
	return out, nil
}

// URL builds a site URL, omitting default ports.
func URL(host string, https bool, port int) string {
	scheme, def := "http", 80
	if https {
		scheme, def = "https", 443
	}
	if port == def {
		return scheme + "://" + host + "/"
	}
	return fmt.Sprintf("%s://%s:%d/", scheme, host, port)
}
